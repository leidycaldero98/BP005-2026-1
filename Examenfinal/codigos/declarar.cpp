#include <iostream> // Incluye la librería para salida en consola.

using namespace std; // Permite usar cout y endl directamente.

int main() { // Inicia la función principal.

    int numero; // Declara una variable entera sin valor inicial definido.

    numero = 10; // Asigna el valor 10 a la variable numero.

    cout << numero << endl; // Muestra el valor almacenado en numero.

    return 0; // Termina el programa correctamente.
}
