#include <iostream> // Incluye la librería de entrada y salida.

using namespace std; // Permite usar cout y endl directamente.

int main() { // Inicia la función principal.

    int a = 10; // Declara una variable entera con valor 10.
    int b = 3; // Declara una variable entera con valor 3.

    cout << a + b << endl; // Calcula y muestra la suma.
    cout << a - b << endl; // Calcula y muestra la resta.
    cout << a * b << endl; // Calcula y muestra la multiplicación.
    cout << a / b << endl; // Calcula y muestra la división entera.
    cout << a % b << endl; // Calcula y muestra el residuo.

    return 0; // Finaliza el programa correctamente.
}
